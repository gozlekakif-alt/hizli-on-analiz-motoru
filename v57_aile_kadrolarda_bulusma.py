"""V57: Which PREVIOUSLY DEFINED family meets which other family in the SAME draw?

All family roots are derived only from earlier completed hour blocks (last
three hours, plus previous calendar day's last blocks if consecutive).
Pair contact counts only when both WHOLE root sets appear inside one 20-number
draw. Pair union of parents may have 2..20 distinct numbers, and multiple
parents may overlap, so results are NOT independent events. Every chosen
family is frozen before the observed hour, avoiding post-hoc family selection.

Full 72-day analysis of all resulting meetings and chronological family
lineage. Random null: same model on complete simulated 217-draw days.
"""
