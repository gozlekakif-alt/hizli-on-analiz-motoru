    roots=root_families(hour)
    assert (1,2,3,4,5,6,7,8) in roots
    assert all(not (set(x)<set(y)) for x in roots for y in roots if x!=y)
    prior=[{"day":"2026-10-12","hour":"H00",
            "roots":{(1,2,3):2,(11,12,13):2,(1,2):2}}]
    roster=frozen_roster(prior,"2026-10-12","H07")
    assert len(roster)==3
    tr=[row(14,list(range(1,21)))]
    nxt={"roots":{}}
    # Actual exact pair meets both roots 1-2-3 and 11-12-13.
    mask=bitset(tr[0]["nums"])
    assert all(bitset(x)&mask==bitset(x) for x in roster)
    pairs,exps,opts=frozen_candidate_pairs(roster)
