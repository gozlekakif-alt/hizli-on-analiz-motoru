def _selftest():
    from v45_sinyal_kor_test import SLOTS
    def row(pos,nums,day="2026-10-12"):
        return {"day":day,"id":40000+pos,"time":SLOTS[pos-1],
                "pos":pos,"nums":frozenset(nums)}
    a=list(range(1,21))
    b=list(range(1,10))+list(range(21,32))
    c=list(range(1,9))+list(range(41,53))
