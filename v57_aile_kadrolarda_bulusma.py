def main():
    p=argparse.ArgumentParser()
    p.add_argument("--data",default="veri.txt")
    p.add_argument("--day",default=None)
    p.add_argument("--sims",type=int,default=RNG_DAYS)
    p.add_argument("--output",default="v57_artifacts/V57_AILELER_AYNI_CEKILISTE_BULUSMA_TEK_ZIP.zip")
    p.add_argument("--selftest",action="store_true")
    args=p.parse_args()
    if args.selftest:_selftest();return
    if args.sims<1:raise ValueError("sims must be positive")
    source,errors,malformed=parse_txt(Path(args.data))
    complete={day:rows for day,rows in source.items() if len(rows)==217
              and {r["pos"] for r in rows}==set(range(1,218))}
    missing={d:len(r) for d,r in source.items() if d not in complete}
    selected=args.day or sorted(complete)[-1]
