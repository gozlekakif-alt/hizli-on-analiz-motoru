def tag(nums):
    return "-".join(map(str,nums))

def bitset(nums):
    v=0
    for n in nums:v|=1<<(n-1)
    return v

def root_families(rows):
    """All inclusion-maximal pair intersections: exact roots with support>=2.

    No k-wise subset explosion; every root generated by shared elements
    of one of the 66/78 draw pairs in the hour, and then maximized.
    """
    shared=set()
    for i in range(len(rows)):
        a=rows[i]["nums"]
        for j in range(i+1,len(rows)):
            common=frozenset(a&rows[j]["nums"])
            if len(common)>=FAMILY_MIN:
                shared.add(common)
    roots=[]
    for fam in sorted(shared,key=lambda f:(-len(f),tuple(sorted(f)))):
        if not any(fam<=older for older in roots):
            roots.append(fam)
    mapped={}
    for fam in roots:
        f=tuple(sorted(fam))
        mask=bitset(f)
        appearance=sum(mask&bitset(row["nums"])==mask for row in rows)
        assert appearance>=2
        mapped[f]=appearance
    return mapped

def hour_structure(rows):
    output=[]
    for b in BLOCKS:
        subset=[rows[i-1] for i in range(b["start"],b["end"]+1)]
        output.append({"hour":b["code"],"time":b["name"],
                       "draws":subset,
                       "roots":root_families(subset)})
    return output

def frozen_roster(context, day, hour, last_n=PREVIOUS_HOURS):
    """Select exactly prior completed hours; no leakage from current hour."""
    selected=[]
    for item in reversed(context):
        if (date.fromisoformat(day)-date.fromisoformat(item["day"])).days>1:
            break
        selected.append(item)
        if len(selected)>=last_n:break
    sources=defaultdict(list)
    for item in selected:
        for family,count in item["roots"].items():
            sources[family].append({"day":item["day"],"hour":item["hour"],
                                    "within_hour_support":count})
    return sources

def _random_prob_of_union(k):
    if k>20:return 0
    if k<0:raise ValueError
    p=1.0
    for t in range(k):p*=(20-t)/(80-t)
    return p
PROBS={k:_random_prob_of_union(k) for k in range(21)}

def frozen_candidate_pairs(roster):
    names=sorted(roster)
    mask={fam:bitset(fam) for fam in names}
    out=[]
    expected=defaultdict(float)
    opportunities=Counter()
    for i,a in enumerate(names):
        for b in names[i+1:]:
            join=mask[a]|mask[b]
            k=join.bit_count()
            if k>20:continue
            intersection=(mask[a]&mask[b]).bit_count()
            relation=("AYRI_KOK" if intersection==0 else
                      "ALT_UST" if intersection==min(len(a),len(b)) else
                      "KISMEN_ORTAK")
            group=(relation,k)
            expected[group]+=PROBS[k]
            opportunities[group]+=1
            out.append((a,b,mask[a],mask[b],join,k,intersection,relation))
    return out,expected,opportunities

def matching_roots(mask,roster):
    return [f for f in sorted(roster) if bitset(f)&mask==bitset(f)]

def _next_hour_lineage(day,source,targets,new_roots,source_block,code):
    """Root transforms: whole continuation, one-number swap, retained parts,
    growth or disappearance. These are observations, not causal families.
    """
    out=[]
    t_masks=[bitset(r["nums"]) for r in targets]
    for fam,origins in sorted(source.items(),key=lambda p:(-len(p[0]),p[0])):
        mask=bitset(fam)
        exact_hits=sum(mask&m==mask for m in t_masks)
        if exact_hits:
            best_kind="TAM_AILE_BULUSTU"
            best=fam
            overlap=len(fam)
            lost=0
        else:
            same_size=[(len(set(fam)&set(g)),g)
                       for g in new_roots if len(g)==len(fam) and g!=fam]
            if same_size:
                overlap,best=max(same_size,key=lambda x:(x[0],tuple(-n for n in x[1])))
            else: overlap,best=0,()
            if overlap==len(fam)-1:
                best_kind="BIR_SAYI_DEGISTIRDI"
                lost=1
            else:
                best_parts=[len(set(fam)&r["nums"]) for r in targets]
                best_overlap=max(best_parts,default=0)
                best_kind="PARCALI_GELDI" if best_overlap>0 else "HIC_GELMEDI"
                lost=len(fam)-best_overlap
        split=(len(fam)>2 and sum(
          len(set(fam)&set(root))==len(fam)-1
          for root in new_roots if len(root)==len(fam)-1)>=2)
        expand=any(set(fam)<set(root) for root in new_roots)
        difference_a=sorted(set(fam)-set(best))
        difference_b=sorted(set(best)-set(fam))
        out.append({"day":day,"target_hour":code,
          "family":tag(fam),"k":len(fam),
          "latest_origin_hour":origins[0]["hour"],"origin_count":len(origins),
          "draws_with_whole_family":exact_hits,"transition":best_kind,
          "closest_new_root":tag(best),"family_overlap":overlap,
          "departed":tag(difference_a),"arrived":tag(difference_b),
          "departed_bands":tag(sorted((n-1)//10+1 for n in difference_a)),
          "arrived_bands":tag(sorted((n-1)//10+1 for n in difference_b)),
          "split_alternative":int(split),"grows_in_new_root":int(expand),
          "overnight_boundary":int(source_block is not None and
                                   source_block.get("day")!=day)})
    return out

def _collect_day(day,rows,context=None,keep_details=True):
    """Return exact meeting records for day, plus frozen expected exposure."""
    context=list(context or [])
    events=[]
    hour_stats=[]
    lineage=[]
    locked=[]
    by_pair=Counter()
    expectation=defaultdict(float)
    chance_slots=Counter()
    class_summary=Counter()
    roots_hour=hour_structure(rows)
    for hour in roots_hour:
        frozen=frozen_roster(context,day,hour["hour"])
        candidates,exps,opps=frozen_candidate_pairs(frozen)
        bymask=defaultdict(list)
        # Current hour complete-day roots may be checked as post-event
        # annotation only, never as candidate parents.
        t_masks=[bitset(r["nums"]) for r in hour["draws"]]
        for pair in candidates:
            a,b,mask_a,mask_b,union,size,inter,relation=pair
            bymask[union].append(pair)
        n=len(hour["draws"])
        for (rel,k),exp in exps.items():
            expectation[(rel,k)]+=exp*n
        for key,matches in opps.items():
            chance_slots[key]+=matches*n
        hour_meets=Counter()
        seen_pair=Counter()
        hour_pair_acts=Counter()
        for idx,draw in enumerate(hour["draws"]):
            drawn=t_masks[idx]
            found=matching_roots(drawn,frozen)
            for fam in found:
                hour_pair_acts[fam]+=1
            for a,b in combinations(found,2):
                parents=(a,b) if a<b else (b,a)
                union=bitset(a)|bitset(b)
                united=tuple(i for i in range(1,81) if union&(1<<(i-1)))
                overlap=tuple(sorted(set(a)&set(b)))
                category=("AYRI_KOK" if not overlap else
                          "ALT_UST" if len(overlap)==min(len(a),len(b))
                          else "KISMEN_ORTAK")
                event={"day":day,"hour":hour["hour"],"time":draw["time"],
                       "draw_id":draw["id"],"slot":draw["pos"],
                       "family_a":tag(a),"family_b":tag(b),
                       "a_size":len(a),"b_size":len(b),
                       "a_origin":frozen[a][0]["hour"],
                       "b_origin":frozen[b][0]["hour"],
                       "a_origin_count":len(frozen[a]),
                       "b_origin_count":len(frozen[b]),
                       "relationship":category,
                       "shared":tag(overlap),"shared_count":len(overlap),
                       "a_only":tag(sorted(set(a)-set(b))),
                       "b_only":tag(sorted(set(b)-set(a))),
                       "union":tag(united),"union_size":len(united),
                       "union_remaining_draw":tag(sorted(draw["nums"]-frozenset(united))),
                       "union_hits_in_this_hour":0,
                       "repeated_union_in_hour":0,
                       "fair_union_prob":round(PROBS[len(united)],11),
                       "night_or_day_boundary":int(
                          any(x["day"]!=day for f in (a,b) for x in frozen[f]))}
                if keep_details:events.append(event)
                pairkey=(a,b)
                seen_pair[pairkey]+=1
                by_pair[pairkey]+=1
                class_summary[(category,len(united))]+=1
                hour_meets[(category,len(united))]+=1
        # Return whether full union of both old parents really recurs >=2 times
        # later in the same hour; this NEVER defines who was frozen.
        if keep_details:
            for event in events:
                if event["day"]==day and event["hour"]==hour["hour"]:
                    target=frozenset(map(int,event["union"].split("-")))
                    occurrence=sum(target<=d["nums"] for d in hour["draws"])
                    event["union_hits_in_this_hour"]=occurrence
                    event["repeated_union_in_hour"]=int(occurrence>=2)
        src=context[-1] if context else None
        if keep_details:
            lineage.extend(_next_hour_lineage(day,frozen,hour["draws"],
                              hour["roots"],src,hour["hour"]))
            locked.append({"day":day,"hour":hour["hour"],
                           "parents_locked_before_hour":len(frozen),
                           "roots_discovered_after_hour":len(hour["roots"]),
                           "parent_families":"|".join(tag(f) for f in sorted(frozen))})
        hour_stats.append({"day":day,"hour":hour["hour"],
            "draws":n,"old_families_locked":len(frozen),
            "new_roots":len(hour["roots"]),
            "frozen_pair_opportunities":len(candidates),
            "meeting_event_count":sum(seen_pair.values()),
            "distinct_meeting_pairs":len(seen_pair),
            "new_pairs_disjoint":sum(v for (rel,k),v in hour_meets.items()
                                     if rel=="AYRI_KOK"),
            "new_pairs_overlap":sum(v for (rel,k),v in hour_meets.items()
                                     if rel=="KISMEN_ORTAK"),
            "new_pairs_nested":sum(v for (rel,k),v in hour_meets.items()
                                     if rel=="ALT_UST"),
            "fair_expected_meetings":round(sum(exps.values())*n,4)})
        context.append({"day":day,"hour":hour["hour"],
                        "roots":hour["roots"]})
        context=context[-PREVIOUS_HOURS:]
    return {"events":events,"by_pair":by_pair,"hour_stats":hour_stats,
            "family_lineage":lineage,"frozen":locked,
            "class_summary":class_summary,
            "expected":expectation,"slots":chance_slots,
            "tail_context":context}

def _all_days(full,selected):
    prior=[]
    events_all=[]
    selected_data=None
    by_pair=Counter();summary=Counter()
    expected=defaultdict(float);opportunities=Counter()
    hours=[]; day_stats=[]
    pair_dates=defaultdict(set);pair_first={}
    for day,rows in sorted(full.items()):
        if prior and (date.fromisoformat(day)-date.fromisoformat(prior[-1]["day"])).days>1:
            prior=[]
        detailed=_collect_day(day,rows,prior,keep_details=True)
        prior=detailed["tail_context"]
        events_all.extend(detailed["events"])
        by_pair.update(detailed["by_pair"])
        summary.update(detailed["class_summary"])
        for k,v in detailed["expected"].items():expected[k]+=v
        opportunities.update(detailed["slots"])
        hours.extend(detailed["hour_stats"])
        for ev in detailed["events"]:
            pair=(ev["family_a"],ev["family_b"])
            pair_dates[pair].add(day)
            pair_first.setdefault(pair,ev)
        day_stats.append({"day":day,
            "hours":len(detailed["hour_stats"]),
            "draws":len(rows),
            "meetings":len(detailed["events"]),
            "distinct_meetings":len(detailed["by_pair"]),
            "disjoint":sum(v for (kind,k),v in detailed["class_summary"].items()
                           if kind=="AYRI_KOK"),
            "partial_overlap":sum(v for (kind,k),v in detailed["class_summary"].items()
                           if kind=="KISMEN_ORTAK"),
            "nested":sum(v for (kind,k),v in detailed["class_summary"].items()
                           if kind=="ALT_UST"),
            "fair_expected":round(sum(detailed["expected"].values()),4)})
        if day==selected:selected_data=detailed
    pair_rows=[]
    for (a,b),count in by_pair.items():
        example=pair_first[(a,b)]
        pair_rows.append({
          "family_a":a,"family_b":b,"count":count,"different_days":len(pair_dates[(a,b)]),
          "overlap_type":example["relationship"],
          "union_size":example["union_size"],
          "union":example["union"],
          "first_day":example["day"],"first_draw_id":example["draw_id"],
          "first_time":example["time"],"first_origin_hours":
             example["a_origin"]+"|"+example["b_origin"]})
    pair_rows.sort(key=lambda p:(-p["count"],-p["different_days"],
                                   p["family_a"],p["family_b"]))
    null=[]
    for key in sorted(set(expected)|set(summary)):
        rel,k=key
        actual=summary[key]
        exp=expected[key]
        null.append({"relation":rel,"union_size":k,
            "actual_meetings":actual,"fair_independent_expected":round(exp,5),
            "difference":round(actual-exp,5),
            "observed_per_opportunity":round(actual/opportunities[key],9)
                 if opportunities[key] else 0,
            "fair_probability":round(PROBS[k],9),
            "potential_pair_target_exposures":opportunities[key]})
    return {"selected":selected_data,"events_all":events_all,
            "top_pairs":pair_rows,"summary":null,"day_stats":day_stats,
            "hour_stats":hours,"selected_day":selected,
            "days":len(full),"all_event_count":len(events_all)}

def _simulated(rows,seed):
    rg=random.Random(seed)
    return [{"id":800000+i,"pos":i+1,"time":r["time"],
             "day":r.get("day","SANAL"),
             "nums":frozenset(rg.sample(range(1,81),20))}
            for i,r in enumerate(rows)]

def rng_sample(full,selected,simulations=RNG_DAYS):
    raw=full[selected]
    rng_counts=[]
    for i in range(simulations):
        random_day=_simulated(raw,578000+i)
        d=_collect_day(selected,random_day,keep_details=False)
        rng_counts.append({
            "total":sum(d["class_summary"].values()),
            "disjoint":sum(v for (kind,n),v in d["class_summary"].items()
                          if kind=="AYRI_KOK"),
            "overlap":sum(v for (kind,n),v in d["class_summary"].items()
                          if kind=="KISMEN_ORTAK"),
            "nested":sum(v for (kind,n),v in d["class_summary"].items()
                          if kind=="ALT_UST"),
            "expected":sum(d["expected"].values())})
    real=_collect_day(selected,raw,keep_details=False)
    recorded={"total":sum(real["class_summary"].values()),
              "disjoint":sum(v for (typ,k),v in real["class_summary"].items()
                      if typ=="AYRI_KOK"),
              "overlap":sum(v for (typ,k),v in real["class_summary"].items()
                      if typ=="KISMEN_ORTAK"),
              "nested":sum(v for (typ,k),v in real["class_summary"].items()
                      if typ=="ALT_UST"),
              "expected":sum(real["expected"].values())}
    return [
      {"metric":metric,"observed":round(recorded[metric],5),
       "rng_mean":round(statistics.mean(s[metric] for s in rng_counts),5),
       "rng_min":min(s[metric] for s in rng_counts),
       "rng_max":max(s[metric] for s in rng_counts),
       "upper_tail_p_exploratory":round((1+sum(
          s[metric]>=recorded[metric] for s in rng_counts))/(simulations+1),5),
       "sim_days":simulations}
      for metric in ("total","disjoint","overlap","nested","expected")]

def _csv(z,name,items,columns=()):
    with z.open(name,"w",force_zip64=True) as fd:
        writer=io.TextIOWrapper(fd,encoding="utf-8",newline="")
        header=list(items[0]) if items else list(columns)
        csvwriter=csv.DictWriter(writer,fieldnames=header)
        csvwriter.writeheader()
        if items:csvwriter.writerows(items)
        writer.flush();writer.detach()

